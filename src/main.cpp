// Mount guard, same shape as adsReady(): probe before use, and only retry an
// absent card every SD_REPROBE_MS so a missing or dead card never stalls the
// pot feed for long. Returns false if there is no usable card, and every
// caller treats that as "no store available" rather than an error worth
// blocking on.
bool sdReady() {
  if (sd_mounted) return true;

  unsigned long now = millis();
  if (sd_probedOnce && now - sdProbe_previousMillis < SD_REPROBE_MS) return false;
  sd_probedOnce = true;
  sdProbe_previousMillis = now;

  // Hand SD the instance TFT_eSPI actually drives this bus with.
  if (SD.begin(SD_CS_PIN, tft.getSPIinstance(), SD_SPI_HZ)) {
    sd_mounted = true;
    Serial.println(F("microSD mounted"));
  } else {
    SD.end();   // release so the next probe starts clean
  }
  return sd_mounted;
}


// Read FACES.TXT and stream it to the controller as one "FACE:" line each,
// then "FACE_END:<n>". The controller only treats a dump as complete when the
// count matches, so a partial read just gets re-requested.
void facesSendDump() {
  // -1 means "no card to read", which is a different answer from a mounted
  // card holding no faces yet (0). The controller keeps asking on -1, so a
  // card inserted later gets picked up without a reboot.
  if (!sdReady()) { Serial1.print(F("FACE_END:-1\n")); return; }

  File f = SD.open(FACES_PATH, FILE_READ);
  if (!f) {
    // Mounted with no file yet, or the card was pulled since it mounted. Tell
    // the two apart, so a pulled card reads as "no card" and is re-probed.
    File root = SD.open("/");
    if (!root) {
      sd_mounted = false;
      SD.end();
      Serial1.print(F("FACE_END:-1\n"));
      return;
    }
    root.close();
    Serial1.print(F("FACE_END:0\n"));
    return;
  }

  uint8_t n = 0;
  char    line[FACE_LINE_MAX + 1];
  while (f.available() && n < FACE_MAX) {
    size_t len = f.readBytesUntil('\n', line, FACE_LINE_MAX);
    line[len] = '\0';
    // Trim any trailing CR from a card written on Windows.
    while (len && (line[len - 1] == '\r' || line[len - 1] == ' ')) line[--len] = '\0';
    if (len < 3) continue;            // blank or junk line, skip it
    Serial1.printf("FACE:%s\n", line);
    n++;
  }
  f.close();
  Serial1.printf("FACE_END:%u\n", n);
}


// Persist one face. body is "<key>,<v0>,..,<v10>,<toggles>" exactly as it will
// be stored. The whole file is rewritten so a re-save of an existing key
// replaces it in place rather than appending a second record for that key.
//
// Answers "FACEOK:<key>" or "FACEERR:<key>" so the controller knows whether
// its NVS copy is confirmed on the card or still only cached locally.
void faceSaveToSD(const char *body) {
  char key = body[0];

  if (!sdReady()) { Serial1.printf("FACEERR:%c\n", key); return; }

  // Slurp what is there, dropping any existing record for this key.
  static char keep[FACE_MAX][FACE_LINE_MAX + 1];
  uint8_t kept = 0;
  File in = SD.open(FACES_PATH, FILE_READ);
  if (in) {
    char line[FACE_LINE_MAX + 1];
    while (in.available() && kept < FACE_MAX - 1) {
      size_t len = in.readBytesUntil('\n', line, FACE_LINE_MAX);
      line[len] = '\0';
      while (len && (line[len - 1] == '\r' || line[len - 1] == ' ')) line[--len] = '\0';
      if (len < 3) continue;
      if (line[0] == key) continue;   // superseded by this save
      strncpy(keep[kept], line, FACE_LINE_MAX);
      keep[kept][FACE_LINE_MAX] = '\0';
      kept++;
    }
    in.close();
  }

  // Rewrite from scratch. FILE_WRITE truncates on this core.
  File out = SD.open(FACES_PATH, FILE_WRITE);
  if (!out) {
    sd_mounted = false;             // card pulled or gone bad, re-probe later
    SD.end();
    Serial1.printf("FACEERR:%c\n", key);
    return;
  }
  bool ok = true;
  for (uint8_t i = 0; i < kept; i++)
    if (out.printf("%s\n", keep[i]) <= 0) ok = false;
  if (out.printf("%s\n", body) <= 0) ok = false;
  out.close();

  if (!ok) { sd_mounted = false; SD.end(); }
  Serial1.printf(ok ? "FACEOK:%c\n" : "FACEERR:%c\n", key);
}


